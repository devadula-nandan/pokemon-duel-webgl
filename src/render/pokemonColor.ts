/** Stable fallback color from name when not in the palette. */
function hashColor(name: string): number {
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0;
  const hue = (h % 360) / 360;
  // Avoid muddy greys — keep saturation/lightness pleasant
  const s = 0.55 + ((h >>> 8) % 30) / 100;
  const l = 0.48 + ((h >>> 16) % 20) / 100;
  // Manual HSL → hex
  const a = s * Math.min(l, 1 - l);
  const f = (n: number) => {
    const k = (n + hue * 12) % 12;
    const col = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
    return Math.round(255 * col);
  };
  return (f(0) << 16) | (f(8) << 8) | f(4);
}

export function pokemonColor(name: string): number {
  return COLORS[name] ?? hashColor(name);
}
